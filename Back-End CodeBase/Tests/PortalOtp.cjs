const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),crypto=require('node:crypto');
const {post,readOtp,loginWithOtp}=require('./PortalIntegration.cjs');
let checks=0;
const assertCheck=(condition,message)=>{assert(condition,message);checks++;};
async function main(){
 const suffix=crypto.randomBytes(5).toString('hex');
 const admin=await loginWithOtp('Demo2');
 let snapshot=await post('Workspace/GetData',{},admin.jwtToken);
 const batch=snapshot['teacher-training-batch-plan-uses'].find(b=>b.batchCode==='BATCH-DEMO-NOV');
 assertCheck(batch?.openRegistration,'Seeded public batch must be open.');
 await post('Public/Register',{batchCode:batch.batchCode,name:'No OTP',email:'unverified@example.test'},undefined,400);checks++;
 const pending=await post('Account/Login',{userName:'Demo8',password:'demo1@123'});
 assertCheck(!pending.jwtToken,'A password alone must not issue a JWT.');
 const login=await post('Account/VerifyLogin',{challengeId:pending.challengeId,otp:readOtp(pending.challengeId)});
 assertCheck(!!login.jwtToken,'OTP verification must issue a JWT.');
 await post('Account/VerifyLogin',{challengeId:pending.challengeId,otp:readOtp(pending.challengeId)},undefined,400);checks++;
 const request={batchCode:batch.batchCode,name:'Sample OTP Trainee '+suffix,email:'otp-'+suffix+'@example.test',phone:'',category:'Teacher',consentProvided:true};
 const challenge=await post('Public/RequestRegistration',request);
 assertCheck(Date.parse(challenge.expiresAt)>Date.now() && Date.parse(challenge.expiresAt)<=Date.now()+301000,'OTP expires in five minutes.');
 await post('Account/VerifyLogin',{challengeId:challenge.challengeId,otp:readOtp(challenge.challengeId)},undefined,400);checks++;
 const registration=await post('Public/Register',{challengeId:challenge.challengeId,otp:readOtp(challenge.challengeId),name:'FORGED',batchCode:'FORGED'});
 assertCheck(registration.newAccount && registration.accountMailPath,'New account details delivered to local outbox.');
 await post('Public/Register',{challengeId:challenge.challengeId,otp:readOtp(challenge.challengeId)},undefined,400);checks++;
 snapshot=await post('Workspace/GetData',{},admin.jwtToken);
 const person=snapshot['teacher-training-trainees'].find(t=>t.id===registration.traineeId);
 assertCheck(person?.name===request.name,'Registration is bound to verified details.');
 const enrollment=snapshot['teacher-training-registrations'].find(r=>r.id===registration.registrationId);
 assertCheck(enrollment?.status==='Pending','Registration begins pending review.');
 const accountMail=fs.readFileSync(path.join(__dirname,'../.local/mail-outbox',registration.accountMailPath.split('/').pop()+'.eml'),'utf8');
 const initialPassword=/Initial password: (.+)/.exec(accountMail)[1].trim();
 const trainee=await loginWithOtp(request.email,initialPassword);
 assertCheck(trainee.user.role==='trainee','A registered email can sign in to the trainee role.');
 const own=await post('Workspace/GetData',{},trainee.jwtToken);
 assertCheck(own['teacher-training-trainees'].every(t=>t.id===registration.traineeId),'New trainee sees their own records.');
 await post('Registrations/SaveData',{upserts:[{...enrollment,status:'Approved',approvalStatus:'Approved',approved:true}],deletes:[]},admin.jwtToken);checks++;
 const after=await post('Workspace/GetData',{},trainee.jwtToken);
 assertCheck(after['teacher-training-registrations'].some(r=>r.id===registration.registrationId && r.status==='Approved'),'Approval survives a fresh database read.');
 const recovery=await post('Public/RequestRecovery',{contact:request.email});
 const recovered=await post('Public/VerifyRecovery',{requestId:recovery.requestId,otp:readOtp(recovery.requestId)});
 assertCheck(recovered.traineeIds.includes(registration.traineeId),'OTP recovery returns the registered trainee ID.');
 const reset=await post('Account/RequestPasswordReset',{userName:request.email});
 const changedPassword='LocalVerification!'+suffix;
 await post('Account/ResetPassword',{challengeId:reset.challengeId,otp:readOtp(reset.challengeId),newPassword:changedPassword});checks++;
 await post('Workspace/GetData',{},trainee.jwtToken,401);checks++;
 const changed=await loginWithOtp(request.email,changedPassword);
 assertCheck(changed.user.role==='trainee','New password works after OTP reset.');
 const demoReset=await post('Account/RequestPasswordReset',{userName:'Demo1'});
 await post('Account/ResetPassword',{challengeId:demoReset.challengeId,otp:readOtp(demoReset.challengeId),newPassword:changedPassword},undefined,400);checks++;
 const demo=await loginWithOtp('Demo1');assertCheck(demo.user.userId==='Demo1','Demo password is unchanged.');
 const retry=await post('Public/RequestRegistration',{...request,email:'locked-'+suffix+'@example.test'});
 const wrong=readOtp(retry.challengeId)==='000000'?'111111':'000000';
 for(let i=0;i<3;i++){await post('Public/Register',{challengeId:retry.challengeId,otp:wrong},undefined,400);checks++;}
 await post('Public/Register',{challengeId:retry.challengeId,otp:readOtp(retry.challengeId)},undefined,400);checks++;
 await post('Public/RequestRegistration',{...request,email:'locked-'+suffix+'@example.test'},undefined,400);checks++;
 console.log(`PASS: ${checks} OTP, open registration, email login, role scope and approval checks.`);
 fs.writeFileSync(path.join(__dirname,'../.local/otp-test-result.json'),JSON.stringify({passed:true,checks,sampleTraineeId:registration.traineeId,time:new Date().toISOString()},null,2));
}
main().catch(error=>{console.error(error.message);process.exitCode=1;});
